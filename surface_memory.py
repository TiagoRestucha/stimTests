"""Rotated surface-code memory circuits with device-specific circuit-level noise.

Stim's built-in generator only supports *uniform* noise. To model distinct
devices (the "fingerprint" of a chip) we generate a noiseless circuit and then
insert noise ourselves, with a per-qubit scale factor drawn once per device and
held fixed across all QEC rounds (as in Sec. 5.1.4 of Umbrarescu et al.).

Noise model (uniform-depolarizing, SD6-like, scaled per qubit by s_q):
  * after 1q Clifford     : DEPOLARIZE1(p * s_q)
  * after 2q Clifford     : DEPOLARIZE2(p * mean(s_a, s_b))
  * after reset           : X_ERROR / Z_ERROR(p * s_q)
  * before measurement    : X_ERROR / Z_ERROR(p * s_q)
  * idle in a TICK layer  : DEPOLARIZE1(p * s_q)
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import stim

_ONE_QUBIT_CLIFFORDS = frozenset({"H", "S", "S_DAG", "SQRT_X", "SQRT_X_DAG", "X", "Y", "Z", "I"})
_TWO_QUBIT_CLIFFORDS = frozenset({"CX", "CZ", "CY", "SWAP", "ISWAP"})
_Z_BASIS_RESETS = frozenset({"R", "RZ"})
_X_BASIS_RESETS = frozenset({"RX"})
_Z_BASIS_MEASURES = frozenset({"M", "MZ"})
_X_BASIS_MEASURES = frozenset({"MX"})
_Z_MEASURE_RESETS = frozenset({"MR", "MRZ"})
_ANNOTATIONS = frozenset({"DETECTOR", "OBSERVABLE_INCLUDE", "QUBIT_COORDS", "SHIFT_COORDS"})

MAX_PROBABILITY = 0.5


@dataclass(frozen=True)
class DeviceNoise:
    """A device fingerprint: a base error rate and a spatial inhomogeneity.

    `inhomogeneity` is the std-dev of the multiplicative scale factor
    s_q ~ N(1, inhomogeneity), clipped to be non-negative. `seed` selects the
    concrete chip realisation (different seeds == different physical chips).
    """

    name: str
    p: float
    inhomogeneity: float = 0.0
    seed: int = 0

    def __post_init__(self) -> None:
        if not 0.0 <= self.p <= MAX_PROBABILITY:
            raise ValueError(f"p must lie in [0, {MAX_PROBABILITY}], got {self.p}")
        if self.inhomogeneity < 0.0:
            raise ValueError(f"inhomogeneity must be >= 0, got {self.inhomogeneity}")

    def qubit_error_rate(self, coord: tuple[float, ...]) -> float:
        """Error rate p * s_q of the qubit at lattice coordinate `coord`.

        Keyed on (seed, coordinate) so the same physical qubit keeps the same
        rate when the patch distance grows — a larger patch is the same chip
        plus extra qubits, as on real hardware.
        """
        if self.inhomogeneity == 0.0:
            return self.p
        key = [self.seed] + [int(round(2 * c)) + 1000 for c in coord]
        scale = np.random.default_rng(key).normal(1.0, self.inhomogeneity)
        return float(np.clip(self.p * max(scale, 0.0), 0.0, MAX_PROBABILITY))


def noiseless_memory_circuit(distance: int, rounds: int, basis: str = "z") -> stim.Circuit:
    """Noiseless rotated surface-code memory experiment generated by Stim."""
    if distance < 2:
        raise ValueError(f"distance must be >= 2, got {distance}")
    if rounds < 1:
        raise ValueError(f"rounds must be >= 1, got {rounds}")
    if basis not in ("x", "z"):
        raise ValueError(f"basis must be 'x' or 'z', got {basis!r}")
    return stim.Circuit.generated(
        f"surface_code:rotated_memory_{basis}", distance=distance, rounds=rounds
    )


def _append_per_target(out: stim.Circuit, gate: str, targets: list[int], rates: np.ndarray) -> None:
    for q in targets:
        if rates[q] > 0.0:
            out.append(gate, [q], float(rates[q]))


def _add_noise(circuit: stim.Circuit, rates: np.ndarray, all_qubits: list[int]) -> stim.Circuit:
    """Return a new circuit with device noise inserted (input is not mutated)."""
    out = stim.Circuit()
    touched: set[int] = set()

    for inst in circuit:
        if isinstance(inst, stim.CircuitRepeatBlock):
            body = _add_noise(inst.body_copy(), rates, all_qubits)
            out.append(stim.CircuitRepeatBlock(inst.repeat_count, body))
            continue

        name = inst.name
        qubits = [t.value for t in inst.targets_copy() if t.is_qubit_target]

        if name == "TICK":
            idle = [q for q in all_qubits if q not in touched]
            _append_per_target(out, "DEPOLARIZE1", idle, rates)
            out.append(inst)
            touched = set()
            continue

        if name in _ANNOTATIONS:
            out.append(inst)
            continue

        touched.update(qubits)

        if name in _Z_BASIS_MEASURES:
            _append_per_target(out, "X_ERROR", qubits, rates)
            out.append(inst)
        elif name in _X_BASIS_MEASURES:
            _append_per_target(out, "Z_ERROR", qubits, rates)
            out.append(inst)
        elif name in _Z_MEASURE_RESETS:
            _append_per_target(out, "X_ERROR", qubits, rates)
            out.append(inst)
            _append_per_target(out, "X_ERROR", qubits, rates)
        elif name in _Z_BASIS_RESETS:
            out.append(inst)
            _append_per_target(out, "X_ERROR", qubits, rates)
        elif name in _X_BASIS_RESETS:
            out.append(inst)
            _append_per_target(out, "Z_ERROR", qubits, rates)
        elif name in _ONE_QUBIT_CLIFFORDS:
            out.append(inst)
            _append_per_target(out, "DEPOLARIZE1", qubits, rates)
        elif name in _TWO_QUBIT_CLIFFORDS:
            out.append(inst)
            for a, b in zip(qubits[::2], qubits[1::2]):
                pair_rate = float(min(MAX_PROBABILITY, 0.5 * (rates[a] + rates[b])))
                if pair_rate > 0.0:
                    out.append("DEPOLARIZE2", [a, b], pair_rate)
        else:
            raise NotImplementedError(f"No noise rule for instruction {name!r}")

    return out


def noisy_memory_circuit(
    distance: int, device: DeviceNoise, rounds: int | None = None, basis: str = "z"
) -> stim.Circuit:
    """Memory experiment on `device`. Defaults to 3d rounds, as in the paper."""
    n_rounds = 3 * distance if rounds is None else rounds
    clean = noiseless_memory_circuit(distance, n_rounds, basis)
    coords = clean.get_final_qubit_coordinates()
    rates = np.zeros(clean.num_qubits)
    for q, c in coords.items():
        rates[q] = device.qubit_error_rate(tuple(c))
    return _add_noise(clean, rates, sorted(coords.keys()))
